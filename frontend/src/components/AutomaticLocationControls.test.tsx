import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { describe, it, expect, vi } from 'vitest';
import { AutomaticLocationControls } from './AutomaticLocationControls';
import type { SavedMap, AutomaticLocationLayout } from '../topology/savedMapTypes';
import type { LocationDocument } from '../topology/locationTypes';
const location = (id: string, name: string, parent?: string): LocationDocument => ({ location_ref: { ref_type: 'CANONICAL_FACT', entity_type: 'Location', entity_id: id }, name, type: null, parent_location_ref: parent ? { ref_type: 'CANONICAL_FACT', entity_type: 'Location', entity_id: parent } : null });
const locations = [location('a','8'),location('b','808','a'),location('c','823','b'),location('d','U42','c'),location('u10','U10','d'),location('u2','U2','d'),location('other','Other'),location('same1','Same','a'),location('same2','Same','other')];
const initial: AutomaticLocationLayout = { hide_empty: false, containers: { a: { direction: 'HORIZONTAL', order: ['Location:same1','Location:b'] }, other: { direction: 'VERTICAL', order: ['Location:same2'] } } };
const saved = (settings = initial): SavedMap => ({ map_ref: { entity_type: 'SavedMap', entity_id: 'map' }, active_variant_ref: { entity_type: 'MapPresentationVariant', entity_id: 'variant' }, variants: [{ variant_ref: { entity_type: 'MapPresentationVariant', entity_id: 'variant' }, name: 'Test', automatic_layout: settings }], placements: [], cable_routes: [], text_annotations: [], name: 'Test', created_at: '', updated_at: '' });
const node = (path: string) => screen.getByRole('treeitem', { name: 'Корень карты' + path });
const expand = (name: string) => fireEvent.click(screen.getByRole('button', { name: `Развернуть ${name}` }));
describe('automatic layout container picker', () => {
  it('shows canonical hierarchy, natural sibling order, full paths and duplicate names without writing', async () => {
    const onSave = vi.fn();
    render(<AutomaticLocationControls map={saved()} locations={locations} onSave={onSave} />);
    for (const name of ['8','808','823','U42']) expand(name);
    const tree = screen.getByRole('tree');
    const labels = within(tree).getAllByRole('treeitem').map(item => item.textContent);
    expect(labels.indexOf('U2')).toBeLessThan(labels.indexOf('U10'));
    fireEvent.click(node(' / 8 / 808 / 823 / U42'));
    expect(node(' / 8 / 808 / 823 / U42')).toHaveAttribute('aria-selected','true');
    expect(screen.getByRole('status')).toHaveTextContent('Корень карты / 8 / 808 / 823 / U42');
    expand('Other');
    expect(node(' / 8 / Same')).toHaveAttribute('title','Корень карты / 8 / Same');
    expect(node(' / Other / Same')).toBeInTheDocument();
    fireEvent.click(screen.getByRole('button',{ name: 'Свернуть 8' }));
    expect(screen.queryByRole('treeitem',{ name: /U42/ })).not.toBeInTheDocument();
    expect(onSave).not.toHaveBeenCalled();
  });
  it('supports keyboard navigation, expand/collapse and selection', async () => {
    const user = userEvent.setup();
    render(<AutomaticLocationControls map={saved()} locations={locations} onSave={vi.fn()} />);
    node('').focus();
    await user.keyboard('{ArrowDown}{ArrowRight}{ArrowDown}{Enter}');
    expect(node(' / 8 / 808')).toHaveFocus();
    expect(node(' / 8 / 808')).toHaveAttribute('aria-selected','true');
    await user.keyboard('{ArrowLeft}');
    expect(node(' / 8')).toHaveFocus();
    await user.keyboard('{ArrowLeft}');
    expect(node(' / 8')).toHaveAttribute('aria-expanded','false');
  });
  it('selects by identity and preserves other containers and saved layout order after reload', async () => {
    const onSave = vi.fn().mockResolvedValue(undefined);
    const view = render(<AutomaticLocationControls map={saved()} locations={locations} onSave={onSave} />);
    fireEvent.click(node(' / 8'));
    expect(screen.getByRole('combobox',{ name: 'Направление' })).toHaveValue('HORIZONTAL');
    expect(onSave).not.toHaveBeenCalled();
    fireEvent.change(screen.getByRole('combobox',{ name: 'Направление' }),{ target: { value: 'VERTICAL' } });
    await waitFor(() => expect(onSave).toHaveBeenCalledTimes(1));
    const settings = onSave.mock.calls[0][0] as AutomaticLocationLayout;
    expect(settings).toEqual({ ...initial, containers: { ...initial.containers, a: { ...initial.containers.a, direction: 'VERTICAL' } } });
    view.rerender(<AutomaticLocationControls map={saved(settings)} locations={locations.map(l => l.location_ref.entity_id === 'a' ? { ...l, name: 'Renamed' } : l)} onSave={onSave} />);
    expect(node(' / Renamed')).toHaveAttribute('aria-selected','true');
    const moves = screen.getAllByRole('button',{ name: 'Ниже' });
    expect(moves[0].parentElement?.parentElement).toHaveTextContent('Same');
    expect(moves[1].parentElement?.parentElement).toHaveTextContent('808');
    expect(locations[1].parent_location_ref?.entity_id).toBe('a');
    view.unmount();
    render(<AutomaticLocationControls map={saved(settings)} locations={locations} onSave={onSave} />);
    fireEvent.click(node(' / 8'));
    expect(screen.getByRole('combobox',{ name: 'Направление' })).toHaveValue('VERTICAL');
    const reloaded = screen.getAllByRole('button',{ name: 'Ниже' });
    expect(reloaded[0].parentElement?.parentElement).toHaveTextContent('Same');
    expect(reloaded[1].parentElement?.parentElement).toHaveTextContent('808');
  });
});
